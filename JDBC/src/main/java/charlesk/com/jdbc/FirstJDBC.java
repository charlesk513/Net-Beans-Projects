    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
          String name = txt_name.getText().trim();
          String regno = txt_regno.getText().trim();
          
          if(name.isEmpty() || regno.isEmpty()){
              if(name.isEmpty()){
                  JOptionPane.showMessageDialog(this, "Please fill in the name");
                  txt_name.requestFocus();
              }else{
                  JOptionPane.showMessageDialog(this, "Please fill in the Registration number");
                  txt_regno.requestFocus();  
              }
             return;
          }
          String sql = "INSERT INTO student(name, reg_no) VALUES ('"+name+"', '"+regno+"')";
          
          try(
            Connection con = DatabaseConnection.getConnection();
            PreparedStatement pst = con.prepareStatement(sql);
        ){
        int rows = pst.executeUpdate();
        if (rows > 0)
           JOptionPane.showMessageDialog(this, "Data successfully written into the database");
        txt_name.setText("");
        txt_regno.setText("");
        txt_name.requestFocus();
    } catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error, while saving in the database");
        e.printStackTrace();
    }
          
    }//GEN-LAST:event_btn_saveActionPerformed

