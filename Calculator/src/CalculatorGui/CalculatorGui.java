private String formatNumber(double val) {
    if (Double.isInfinite(val)){ 
        return "Zero division Error!";
    }
    else if(Double.isNaN(val)){
    return "Not a number";
    }
    if (val == (long) val) {
        return String.valueOf((long) val);
    }
    return String.valueOf(val);
}
