    @Override
    public void actionPerformed(ActionEvent e) {
    String caption = e.getActionCommand();
        switch (caption) {
            case "ADD":
                if(first_no_txt.getText().equals("")){
                    JOptionPane.showMessageDialog(null, "Please enter the first value to go on");
                    first_no_txt.requestFocus();
                }
                else if(second_no_txt.getText().equals("")){
                    JOptionPane.showMessageDialog(null, "Please enter the second value to go on");
                    second_no_txt.requestFocus();
                }
                else{
                    double a = format(first_no_txt.getText());
                    double b = format(second_no_txt.getText());
                    double sum = a + b;
                    results_txt.setText(String.valueOf(sum));
                }
                break; 
            case "RESET":
                first_no_txt.setText("");
                second_no_txt.setText("");
                results_txt.setText("");
                break;
            case "EXIT":
                System.out.println("Exiting the window");
                System.exit(0);
            default:
                break;
        }
    }
    
    public final void provider(){
        results_txt.setEditable(false);
        add_btn.addActionListener(this);
        reset_btn.addActionListener(this);
        exit_btn.addActionListener(this);
        setLocationRelativeTo(null);
    }
    
    public double format(String var){
        double result;
        try{
            result = Double.parseDouble(var);
            
        } catch (NumberFormatException ex){
            JOptionPane.showMessageDialog(null, "Please enter numbers only\n" + var + " is not a number");
            result = 0.0;     
        } finally{
           System.out.println("Well done, you are safe to go!");
        }
        
        
        return result; 
        
    }
