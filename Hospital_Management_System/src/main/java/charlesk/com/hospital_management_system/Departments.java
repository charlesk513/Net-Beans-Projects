    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findActionPerformed
    String department_id = txt_department_id.getText().trim();

    if(department_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the Department ID to search");
        txt_department_id.requestFocus();
        return;
    }

    String sql = "SELECT * FROM departments WHERE department_id = ?";

    try(Connection findCon = DatabaseConnection.getConnection(); PreparedStatement findPst = findCon.prepareStatement(sql)){

        findPst.setString(1, department_id);

        try(ResultSet findRs = findPst.executeQuery()){

            if(findRs.next()){
                displayDepartment(findRs);
            }else{
                JOptionPane.showMessageDialog(this, "No department found with ID " + department_id);
            }
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error searching department: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_findActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
    String departmentName = txt_name.getText().trim();
    String location = txt_location.getText().trim();
    String phone = txt_phone.getText().trim();

    if(departmentName.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the department name");
        txt_name.requestFocus();
        return;
    }else if(location.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the department location");
        txt_location.requestFocus();
        return;
    }

    String sql = "INSERT INTO departments(department_name, location, phone) VALUES (?, ?, ?)";

    try(Connection saveCon = DatabaseConnection.getConnection(); PreparedStatement savePst = saveCon.prepareStatement(sql)){

        savePst.setString(1, departmentName);
        savePst.setString(2, location);

        if(phone.isEmpty()) savePst.setNull(3, java.sql.Types.VARCHAR);
        else savePst.setString(3, phone);

        int rows = savePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Department successfully saved");
            clear();
            loadDepartments();
            showResultsInTheTable();
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error while saving department: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_saveActionPerformed

