    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findActionPerformed
     String patient_id = txt_patient_id.getText().trim();

    if(patient_id.isEmpty()) {

        JOptionPane.showMessageDialog(this,"Please enter the Patient ID to search");

        txt_patient_id.requestFocus();
        return;
    }

    String sql =
        "SELECT * FROM patients WHERE patient_id = ?";

    try(
        Connection searchCon = DatabaseConnection.getConnection();
        PreparedStatement searchPst =
            searchCon.prepareStatement(sql)
    ) {

        searchPst.setString(1, patient_id);

        try(ResultSet searchRs = searchPst.executeQuery()) {

            if(searchRs.next()) {

                txt_patient_id.setText(searchRs.getString("patient_id"));

                txt_firstname.setText(searchRs.getString("first_name"));

                txt_surname.setText(searchRs.getString("last_name"));

                combo_gender.setSelectedItem(searchRs.getString("gender"));

                date_chooser.setDate(searchRs.getDate("date_of_birth"));

                txt_phone.setText(
                    searchRs.getString("phone"));

                txt_address.setText(
                    searchRs.getString("address"));

            } else {

                JOptionPane.showMessageDialog(this,"No patient found with ID " + patient_id);
            }
        }

    } catch(SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Error searching patient: " + e.getMessage()
        );
    }
    }//GEN-LAST:event_btn_findActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed

    String firstname = txt_firstname.getText().trim();
    String surname = txt_surname.getText().trim();
    String phone = txt_phone.getText().trim();
    String address = txt_address.getText().trim();

    Object selectedGender = combo_gender.getSelectedItem();
    java.util.Date selectedDate = date_chooser.getDate();

    if(firstname.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in the firstname");
        txt_firstname.requestFocus();
        return;
    }else if(surname.isEmpty()) {
        JOptionPane.showMessageDialog(this,"Please fill in the surname");
        txt_surname.requestFocus();
        return;
    }else if(selectedGender == null) {
        JOptionPane.showMessageDialog(this, "Please select gender");
        combo_gender.requestFocus();
        return;
    }else if(selectedDate == null) {
        JOptionPane.showMessageDialog(this, "Please select date of birth");
        return;
    }else if(phone.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in the phone");
        txt_phone.requestFocus();
        return;
    }else if(address.isEmpty()) {
        JOptionPane.showMessageDialog(this,"Please fill in the address");
        txt_address.requestFocus();
        return;
    }

    String gender = selectedGender.toString();

    java.sql.Date dob = new java.sql.Date(selectedDate.getTime());

    String sql = "INSERT INTO patients(first_name, last_name, gender, date_of_birth, phone, address) VALUES (?, ?, ?, ?, ?, ?)";

    try(
        Connection con = DatabaseConnection.getConnection();
        PreparedStatement pst = con.prepareStatement(sql)
    ) {

        pst.setString(1, firstname);
        pst.setString(2, surname);
        pst.setString(3, gender);
        pst.setDate(4, dob);
        pst.setString(5, phone);
        pst.setString(6, address);

        int rows = pst.executeUpdate();

        if(rows > 0) {
            JOptionPane.showMessageDialog(this, "Patient successfully saved" );

            clear();

            loadPatients();
            showResultsInTheTable();

            txt_surname.requestFocus();
        }

    } catch(SQLException e) {
        JOptionPane.showMessageDialog(this, "Error while saving patient: " + e.getMessage()
        );
    }
    }//GEN-LAST:event_btn_saveActionPerformed

