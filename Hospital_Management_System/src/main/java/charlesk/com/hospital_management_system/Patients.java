private void btn_deleteActionPerformed(java.awt.event.ActionEvent evt) {

    String patientId = txt_patient_id.getText().trim();

    if (patientId.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter or select a Patient ID to delete"
        );
        return;
    }

    // Confirm before deleting
    int choice = JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to delete this patient?",
        "Confirm Delete",
        JOptionPane.YES_NO_OPTION
    );

    if (choice != JOptionPane.YES_OPTION) {
        return;
    }

    // Create DTO containing the patient ID
    DataDTO data = new DataDTO();
    data.put("patient_id", patientId);

    // Send DELETE request to the server
    RequestManager.getInstance().sendRequest(
        "PATIENT_GUI",
        "PATIENTS",
        "DELETE",
        data,
        event -> {

            Response response = (Response) event.getSource();

            if (response.isSuccessful()) {

                Object result = response.getData();

                if (result instanceof Number
                        && ((Number) result).intValue() > 0) {

                    JOptionPane.showMessageDialog(
                        this,
                        "Patient deleted successfully"
                    );

                    clear();
                    loadPatients();
                    txt_surname.requestFocus();

                } else {

                    JOptionPane.showMessageDialog(
                        this,
                        "No patient with ID " + patientId
                        + " exists in the database."
                    );
                }

            } else {

                JOptionPane.showMessageDialog(
                    this,
                    "Database error: " + response.getMessage()
                );
            }
        }
    );
}


