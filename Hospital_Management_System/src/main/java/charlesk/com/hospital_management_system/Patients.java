    public final void loadPatients(){
        String sql = "SELECT * FROM patients ORDER BY patient_id";
        try{
            con = DatabaseConnection.getConnection();
            pst = con.prepareStatement(sql, ResultSet.TYPE_SCROLL_INSENSITIVE, ResultSet.CONCUR_READ_ONLY);
            rs = pst.executeQuery();
        } catch(SQLException e){
            JOptionPane.showMessageDialog(this, "Error loading patients information: " + e.getMessage());
        }
    }
    
    public final void showResultsInTheTable() {
        try{
            DefaultTableModel model = (DefaultTableModel) patients_table.getModel();
        
            model.setRowCount(0);
            while(rs.next()){
                Object[] row = {
                    rs.getString("patient_id"),
                    rs.getString("first_name"),
                    rs.getString("last_name"),
                    rs.getString("gender"),
                    rs.getString("date_of_birth"),
                    rs.getString("phone"),
                    rs.getString("address")
                    };
                    model.addRow(row);
            }
            rs.beforeFirst();
        } catch (SQLException e){
            JOptionPane.showMessageDialog(this, "Error loading students" + e.getMessage());
        }
    }
