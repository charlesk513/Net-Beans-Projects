    private void btn_deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_deleteActionPerformed

    String patient_id = txt_patient_id.getText().trim();

    if(patient_id.isEmpty()) {

        JOptionPane.showMessageDialog(this, "Please enter or select a Patient ID to delete" );

        txt_patient_id.requestFocus();
        return;
    }

    int choice = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this patient?","Confirm deletion",JOptionPane.YES_NO_OPTION);

    if(choice != JOptionPane.YES_OPTION) {
        return;
    }

    String sql =
        "DELETE FROM patients WHERE patient_id = ?";

    try(
        Connection con = DatabaseConnection.getConnection();
        PreparedStatement pst = con.prepareStatement(sql)
    ) {

        pst.setString(1, patient_id);

        int rows = pst.executeUpdate();

        if(rows > 0) {

            JOptionPane.showMessageDialog( this, "Patient deleted successfully" );

            clear();

            loadPatients();
            showResultsInTheTable();

            txt_surname.requestFocus();

        } else {

            JOptionPane.showMessageDialog(this, "No patient with ID " + patient_id + " exists in the database." );
        }

    } catch(SQLException e) {

        JOptionPane.showMessageDialog( this,"Database error: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_deleteActionPerformed

