    private void btn_lastActionPerformed(java.awt.event.ActionEvent evt) {
        if (patients.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Empty database, nothing to retrieve");
            return;
        }
        currentIndex = patients.size() - 1;
        displayPatient(patients.get(currentIndex));
    }

    private void btn_nextActionPerformed(java.awt.event.ActionEvent evt) {
        if (patients.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Results have not been loaded");
        } else if (currentIndex < patients.size() - 1) {
            currentIndex++;
            displayPatient(patients.get(currentIndex));
        } else {
            JOptionPane.showMessageDialog(this, "You are at the last row");
        }
    }

    private void btn_previousActionPerformed(java.awt.event.ActionEvent evt) {
        if (patients.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Records are not loaded");
        } else if (currentIndex > 0) {
            currentIndex--;
            displayPatient(patients.get(currentIndex));
        } else {
            JOptionPane.showMessageDialog(this, "You are at the first record");
        }
    }
    
    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {
    String patientId = txt_patient_id.getText().trim();

    if (patientId.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter a patient ID first.");
        txt_patient_id.requestFocus();
        return;
    }

    DataDTO data = new DataDTO();
    data.put("patient_id", patientId);

    RequestManager.getInstance().sendRequest(
        "PATIENT_GUI",
        "PATIENTS",
        "FIND",
        data,
        event -> {
            Response response = (Response) event.getSource();

            if (!response.isSuccessful()) {
                JOptionPane.showMessageDialog(
                    this,
                    "Error finding patient: " + response.getMessage()
                );
                return;
            }

            Object result = response.getData();

            if (result == null) {
                JOptionPane.showMessageDialog(
                    this,
                    "No patient found with ID: " + patientId
                );
                return;
            }

            if (!(result instanceof DataDTO)) {
                JOptionPane.showMessageDialog(
                    this,
                    "Invalid patient data received from server."
                );
                return;
            }

            DataDTO patient = (DataDTO) result;

            // Display the retrieved patient.
            displayPatient(patient);

            // Synchronize the local patient list.
            int index = findPatientIndex(
                String.valueOf(patient.get("patient_id"))
            );

            if (index >= 0) {
                patients.set(index, patient);
            } else {
                patients.add(patient);
                index = patients.size() - 1;
            }

            currentIndex = index;

            // Refresh the table.
            showResultsInTheTable();
        }
    );
}
    
private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {

    // Get values from the form
    String firstname = txt_firstname.getText().trim();
    String surname = txt_surname.getText().trim();
    Object selectedGender = combo_gender.getSelectedItem();
    java.util.Date selectedDate = date_chooser.getDate();
    String phone = txt_phone.getText().trim();
    String address = txt_address.getText().trim();

    // Validate the form
    if (firstname.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in the firstname");
        return;
    }

    if (surname.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in the surname");
        return;
    }

    if (selectedGender == null) {
        JOptionPane.showMessageDialog(this, "Please select gender");
        return;
    }

    if (selectedDate == null) {
        JOptionPane.showMessageDialog(this, "Please select date of birth");
        return;
    }

    if (phone.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in the phone");
        return;
    }

    if (address.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in the address");
        return;
    }

    // Create DTO and store patient information
    DataDTO data = new DataDTO();

    data.put("first_name", firstname);
    data.put("last_name", surname);
    data.put("gender", selectedGender.toString());
    data.put("date_of_birth",
            new java.sql.Date(selectedDate.getTime()));
    data.put("phone", phone);
    data.put("address", address);

    // Send the request to the server
    RequestManager.getInstance().sendRequest(
        "PATIENT_GUI",
        "PATIENTS",
        "SAVE",
        data,
        event -> {

            Response response = (Response) event.getSource();

            if (response.isSuccessful()) {

                Object result = response.getData();

                if (result instanceof Number
                        && ((Number) result).intValue() > 0) {

                    JOptionPane.showMessageDialog(
                        this,
                        "Patient successfully saved"
                    );

                    clear();
                    loadPatients();
                    txt_surname.requestFocus();

                } else {

                    JOptionPane.showMessageDialog(
                        this,
                        "Error saving patient: " + response.getMessage()
                    );
                }

            } else {

                JOptionPane.showMessageDialog(
                    this,
                    "Error saving patient: " + response.getMessage()
                );
            }
        }
    );
}


