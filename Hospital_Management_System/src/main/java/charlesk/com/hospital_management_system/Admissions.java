    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findActionPerformed
    String admission_id = txt_admission_id.getText().trim();

    if(admission_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the Admission ID to search");
        txt_admission_id.requestFocus();
        return;
    }

    String sql = "SELECT * FROM admissions WHERE admission_id = ?";

    try(Connection searchCon = DatabaseConnection.getConnection(); 
            PreparedStatement searchPst = searchCon.prepareStatement(sql))
    {
        searchPst.setString(1, admission_id);

        try(ResultSet searchRs = searchPst.executeQuery()){

            if(searchRs.next()){
                displayAdmission(searchRs);
            }else{
                JOptionPane.showMessageDialog(this, "Admission not found");
            }
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error searching admission: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_findActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
    Object patient = combo_patient.getSelectedItem();
    Object doctor = combo_doctor.getSelectedItem();
    Object ward = combo_ward.getSelectedItem();
    Object status = combo_status.getSelectedItem();
    java.util.Date admissionDate = admission_date.getDate();
    java.util.Date dischargeDate = discharge_date.getDate();
    String reason = txt_admission_reason.getText().trim();

    if(patient == null){
        JOptionPane.showMessageDialog(this, "Please select a patient");
        return;
    }else if(doctor == null){
        JOptionPane.showMessageDialog(this, "Please select a doctor");
        return;
    }else if(ward == null){
        JOptionPane.showMessageDialog(this, "Please select a ward");
        return;
    }else if(admissionDate == null){
        JOptionPane.showMessageDialog(this, "Please select the admission date");
        return;
    }else if(reason.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the admission reason");
        txt_admission_reason.requestFocus();
        return;
    }else if(status == null){
        JOptionPane.showMessageDialog(this, "Please select the status");
        return;
    }

    String patient_id = patient.toString().split(" - ")[0];
    String doctor_id = doctor.toString().split(" - ")[0];
    String ward_id = ward.toString().split(" - ")[0];

    String sql = "INSERT INTO admissions(patient_id, doctor_id, ward_id, admission_date, discharge_date, admission_reason, status) VALUES (?, ?, ?, ?, ?, ?, ?)";

    try(Connection conn = DatabaseConnection.getConnection(); 
            PreparedStatement pt = conn.prepareStatement(sql)){

        pt.setString(1, patient_id);
        pt.setString(2, doctor_id);
        pt.setString(3, ward_id);
        pt.setDate(4, new java.sql.Date(admissionDate.getTime()));

        if(dischargeDate == null) pt.setNull(5, java.sql.Types.DATE);
        else pt.setDate(5, new java.sql.Date(dischargeDate.getTime()));

        pt.setString(6, reason);
        pt.setString(7, status.toString());

        int rows = pt.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Admission successfully saved");
            clear();
            loadAdmissions();
            showResultsInTheTable();
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error while saving admission: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_saveActionPerformed

