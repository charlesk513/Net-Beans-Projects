public void selectComboById(javax.swing.JComboBox<String> combo, String id){
    for(int i = 0; i < combo.getItemCount(); i++){
        if(combo.getItemAt(i).startsWith(id + " - ")){
            combo.setSelectedIndex(i);
            break;
        }
    }
}
