    private void btn_deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_deleteActionPerformed
    String admission_id = txt_admission_id.getText().trim();

    if(admission_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter or select an Admission ID to delete");
        txt_admission_id.requestFocus();
        return;
    }

    int choice = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this admission?", "Confirm deletion", JOptionPane.YES_NO_OPTION);

    if(choice != JOptionPane.YES_OPTION) return;

    String sql = "DELETE FROM admissions WHERE admission_id = ?";

    try(Connection conn = DatabaseConnection.getConnection(); 
            PreparedStatement pt = conn.prepareStatement(sql)){

        pt.setString(1, admission_id);
        int rows = pt.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Admission deleted successfully");
            clear();
            loadAdmissions();
            showResultsInTheTable();
        }else{
            JOptionPane.showMessageDialog(this, "Admission does not exist");
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_deleteActionPerformed

