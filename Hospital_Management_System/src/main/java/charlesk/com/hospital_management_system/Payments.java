public void loadBills(){
    String sql = "SELECT bill_id, total_amount FROM bills ORDER BY bill_id";

    try(Connection billCon = DatabaseConnection.getConnection(); PreparedStatement billPst = billCon.prepareStatement(sql); ResultSet billRs = billPst.executeQuery()){
        combo_bill.removeAllItems();

        while(billRs.next()){
            combo_bill.addItem(billRs.getString("bill_id") + " - " + billRs.getString("total_amount"));
        }

        combo_bill.setSelectedIndex(-1);

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading bills: " + e.getMessage());
    }
}
public void displayPayment(ResultSet data) throws SQLException{
    txt_payment_id.setText(data.getString("payment_id"));
    selectBill(data.getString("bill_id"));
    txt_amount.setText(data.getString("amount"));
    txt_payment_method.setText(data.getString("payment_method"));
    payment_date.setDate(data.getDate("payment_date"));
    txt_reference_no.setText(data.getString("reference_no"));
}
public void selectBill(String bill_id){
    for(int i = 0; i < combo_bill.getItemCount(); i++){
        if(combo_bill.getItemAt(i).startsWith(bill_id + " - ")){
            combo_bill.setSelectedIndex(i);
            break;
        }
    }
}
public void clear() throws SQLException{
    txt_payment_id.setText("");
    combo_bill.setSelectedIndex(-1);
    txt_amount.setText("");
    txt_payment_method.setText("");
    payment_date.setDate(null);
    txt_reference_no.setText("");
}
public void displayCurrentRow() throws SQLException{
    displayPayment(rs);
}public final void loadPayments(){
    String sql = "SELECT * FROM payments ORDER BY payment_id";

    try{
        if(rs != null) rs.close();
        if(pst != null) pst.close();
        if(con != null) con.close();

        con = DatabaseConnection.getConnection();
        pst = con.prepareStatement(sql, ResultSet.TYPE_SCROLL_INSENSITIVE, ResultSet.CONCUR_READ_ONLY);
        rs = pst.executeQuery();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading payments: " + e.getMessage());
    }
}
public final void showResultsInTheTable(){
    try{
        DefaultTableModel model = (DefaultTableModel) payment_table.getModel();
        model.setRowCount(0);

        while(rs.next()){
            Object[] row = {
                rs.getString("payment_id"),
                rs.getString("bill_id"),
                rs.getBigDecimal("amount"),
                rs.getString("payment_method"),
                rs.getDate("payment_date"),
                rs.getString("reference_no")
            };

            model.addRow(row);
        }

        rs.beforeFirst();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading payments: " + e.getMessage());
    }
}

