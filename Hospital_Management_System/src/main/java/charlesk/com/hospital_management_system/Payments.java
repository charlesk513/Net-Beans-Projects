    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findActionPerformed
    String payment_id = txt_payment_id.getText().trim();

    if(payment_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the Payment ID to search");
        txt_payment_id.requestFocus();
        return;
    }

    String sql = "SELECT * FROM payments WHERE payment_id = ?";

    try(Connection findCon = DatabaseConnection.getConnection(); PreparedStatement findPst = findCon.prepareStatement(sql)){

        findPst.setString(1, payment_id);

        try(ResultSet findRs = findPst.executeQuery()){

            if(findRs.next()){
                displayPayment(findRs);
            }else{
                JOptionPane.showMessageDialog(this, "No payment found with ID " + payment_id);
            }
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error searching payment: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_findActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
    Object bill = combo_bill.getSelectedItem();
    String amount = txt_amount.getText().trim();
    String paymentMethod = txt_payment_method.getText().trim();
    String referenceNo = txt_reference_no.getText().trim();
    java.util.Date selectedDate = payment_date.getDate();

    if(bill == null){
        JOptionPane.showMessageDialog(this, "Please select a bill");
        combo_bill.requestFocus();
        return;
    }else if(amount.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the payment amount");
        txt_amount.requestFocus();
        return;
    }else if(paymentMethod.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the payment method");
        txt_payment_method.requestFocus();
        return;
    }else if(referenceNo.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the reference number");
        txt_reference_no.requestFocus();
        return;
    }else if(selectedDate == null){
        JOptionPane.showMessageDialog(this, "Please select the payment date");
        return;
    }

    double paymentAmount;

    try{
        paymentAmount = Double.parseDouble(amount);

        if(paymentAmount <= 0){
            JOptionPane.showMessageDialog(this, "Payment amount must be greater than zero");
            txt_amount.requestFocus();
            return;
        }

    }catch(NumberFormatException e){
        JOptionPane.showMessageDialog(this, "Please enter a valid payment amount");
        txt_amount.requestFocus();
        return;
    }

    String bill_id = bill.toString().split(" - ")[0];
    java.sql.Date paymentDate = new java.sql.Date(selectedDate.getTime());
    String sql = "INSERT INTO payments(bill_id, amount, payment_method, payment_date, reference_no) VALUES (?, ?, ?, ?, ?)";

    try(Connection saveCon = DatabaseConnection.getConnection(); PreparedStatement savePst = saveCon.prepareStatement(sql)){

        savePst.setString(1, bill_id);
        savePst.setDouble(2, paymentAmount);
        savePst.setString(3, paymentMethod);
        savePst.setDate(4, paymentDate);
        savePst.setString(5, referenceNo);

        int rows = savePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Payment successfully saved");
            clear();
            loadPayments();
            showResultsInTheTable();
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error while saving payment: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_saveActionPerformed

