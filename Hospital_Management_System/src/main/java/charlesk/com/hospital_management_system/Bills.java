public void selectAppointment(String appointment_id){
    for(int i = 0; i < combo_appointments.getItemCount(); i++){
        if(combo_appointments.getItemAt(i).startsWith(appointment_id + " - ")){
            combo_appointments.setSelectedIndex(i);
            break;
        }
    }
}
    public void loadAppointments(){
    String sql = "SELECT a.appointment_id, p.first_name, p.last_name, a.appointment_date FROM appointments a INNER JOIN patients p ON a.patient_id = p.patient_id ORDER BY a.appointment_id";

    try(Connection appointmentCon = DatabaseConnection.getConnection(); PreparedStatement appointmentPst = appointmentCon.prepareStatement(sql); ResultSet appointmentRs = appointmentPst.executeQuery()){
        combo_appointments.removeAllItems();

        while(appointmentRs.next()){
            combo_appointments.addItem(appointmentRs.getString("appointment_id") + " - " + appointmentRs.getString("first_name") + " " + appointmentRs.getString("last_name") + " - " + appointmentRs.getDate("appointment_date"));
        }

        combo_appointments.setSelectedIndex(-1);

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading appointments: " + e.getMessage());
    }
}
    public void displayCurrentRow() throws SQLException{
    displayBill(rs);
}
public void displayBill(ResultSet data) throws SQLException{
    txt_bill_id.setText(data.getString("bill_id"));
    selectAppointment(data.getString("appointment_id"));
    txt_amount.setText(data.getString("total_amount"));
    bill_date.setDate(data.getDate("bill_date"));
    combo_status.setSelectedItem(data.getString("status"));
}
public void clear() throws SQLException{
    txt_bill_id.setText("");
    combo_appointments.setSelectedIndex(-1);
    bill_date.setDate(null);
    combo_status.setSelectedIndex(-1);
    txt_amount.setText("");
}
public final void loadBills(){
    String sql = "SELECT * FROM bills ORDER BY bill_id";

    try{
        if(rs != null) rs.close();
        if(pst != null) pst.close();
        if(con != null) con.close();

        con = DatabaseConnection.getConnection();
        pst = con.prepareStatement(sql, ResultSet.TYPE_SCROLL_INSENSITIVE, ResultSet.CONCUR_READ_ONLY);
        rs = pst.executeQuery();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading bills: " + e.getMessage());
    }
}
public final void showResultsInTheTable(){
    try{
        DefaultTableModel model = (DefaultTableModel) bills_table.getModel();
        model.setRowCount(0);

        while(rs.next()){
            Object[] row = {
                rs.getString("bill_id"),
                rs.getString("appointment_id"),
                rs.getBigDecimal("total_amount"),
                rs.getDate("bill_date"),
                rs.getString("status")
            };

            model.addRow(row);
        }

        rs.beforeFirst();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading bills: " + e.getMessage());
    }
}

