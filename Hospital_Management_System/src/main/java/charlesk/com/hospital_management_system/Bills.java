    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findActionPerformed
    String bill_id = txt_bill_id.getText().trim();

    if(bill_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the Bill ID to search");
        txt_bill_id.requestFocus();
        return;
    }

    String sql = "SELECT * FROM bills WHERE bill_id = ?";

    try(Connection findCon = DatabaseConnection.getConnection(); PreparedStatement findPst = findCon.prepareStatement(sql)){

        findPst.setString(1, bill_id);

        try(ResultSet findRs = findPst.executeQuery()){

            if(findRs.next()){
                displayBill(findRs);
            }else{
                JOptionPane.showMessageDialog(this, "No bill found with ID " + bill_id);
            }
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error searching bill: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_findActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
    Object appointment = combo_appointments.getSelectedItem();
    Object status = combo_status.getSelectedItem();
    String amount = txt_amount.getText().trim();
    java.util.Date selectedDate = bill_date.getDate();

    if(appointment == null){
        JOptionPane.showMessageDialog(this, "Please select an appointment");
        combo_appointments.requestFocus();
        return;
    }else if(selectedDate == null){
        JOptionPane.showMessageDialog(this, "Please select the bill date");
        return;
    }else if(status == null){
        JOptionPane.showMessageDialog(this, "Please select the bill status");
        combo_status.requestFocus();
        return;
    }else if(amount.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the total amount");
        txt_amount.requestFocus();
        return;
    }

    double totalAmount;

    try{
        totalAmount = Double.parseDouble(amount);

        if(totalAmount <= 0){
            JOptionPane.showMessageDialog(this, "Total amount must be greater than zero");
            txt_amount.requestFocus();
            return;
        }

    }catch(NumberFormatException e){
        JOptionPane.showMessageDialog(this, "Please enter a valid amount");
        txt_amount.requestFocus();
        return;
    }

    String appointment_id = appointment.toString().split(" - ")[0];
    java.sql.Date billDate = new java.sql.Date(selectedDate.getTime());
    String sql = "INSERT INTO bills(appointment_id, total_amount, bill_date, status) VALUES (?, ?, ?, ?)";

    try(Connection saveCon = DatabaseConnection.getConnection(); PreparedStatement savePst = saveCon.prepareStatement(sql)){

        savePst.setString(1, appointment_id);
        savePst.setDouble(2, totalAmount);
        savePst.setDate(3, billDate);
        savePst.setString(4, status.toString());

        int rows = savePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Bill successfully saved");
            clear();
            loadBills();
            showResultsInTheTable();
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error while saving bill: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_saveActionPerformed

