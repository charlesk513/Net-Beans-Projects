public void loadAppointments(){
    String sql = "SELECT a.appointment_id, p.first_name, p.last_name, a.appointment_date FROM appointments a INNER JOIN patients p ON a.patient_id = p.patient_id ORDER BY a.appointment_id";

    try(Connection appointmentCon = DatabaseConnection.getConnection(); PreparedStatement appointmentPst = appointmentCon.prepareStatement(sql); ResultSet appointmentRs = appointmentPst.executeQuery()){
        combo_appointment.removeAllItems();

        while(appointmentRs.next()){
            combo_appointment.addItem(appointmentRs.getString("appointment_id") + " - " + appointmentRs.getString("first_name") + " " + appointmentRs.getString("last_name") + " - " + appointmentRs.getDate("appointment_date"));
        }

        combo_appointment.setSelectedIndex(-1);

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading appointments: " + e.getMessage());
    }
}
public void displayDiagnosis(ResultSet data) throws SQLException{
    txt_diagnoses_id.setText(data.getString("diagnosis_id"));
    selectAppointment(data.getString("appointment_id"));
    txt_name.setText(data.getString("diagnosis_name"));
    txt_symptoms.setText(data.getString("symptoms"));
    txt_treatment_plan.setText(data.getString("treatment_plan"));
}
public void selectAppointment(String appointment_id){
    for(int i = 0; i < combo_appointment.getItemCount(); i++){
        if(combo_appointment.getItemAt(i).startsWith(appointment_id + " - ")){
            combo_appointment.setSelectedIndex(i);
            break;
        }
    }
}
public void clear() throws SQLException{
    txt_diagnoses_id.setText("");
    combo_appointment.setSelectedIndex(-1);
    txt_name.setText("");
    txt_symptoms.setText("");
    txt_treatment_plan.setText("");
}
public void displayCurrentRow() throws SQLException{
    displayDiagnosis(rs);
}
public final void loadDiagnoses(){
    String sql = "SELECT * FROM diagnoses ORDER BY diagnosis_id";

    try{
        if(rs != null) rs.close();
        if(pst != null) pst.close();
        if(con != null) con.close();

        con = DatabaseConnection.getConnection();
        pst = con.prepareStatement(sql, ResultSet.TYPE_SCROLL_INSENSITIVE, ResultSet.CONCUR_READ_ONLY);
        rs = pst.executeQuery();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading diagnoses: " + e.getMessage());
    }
}
public final void showResultsInTheTable(){
    try{
        DefaultTableModel model = (DefaultTableModel) diagnoses_table.getModel();
        model.setRowCount(0);

        while(rs.next()){
            Object[] row = {
                rs.getString("diagnosis_id"),
                rs.getString("appointment_id"),
                rs.getString("diagnosis_name"),
                rs.getString("symptoms"),
                rs.getString("treatment_plan")
            };

            model.addRow(row);
        }

        rs.beforeFirst();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading diagnoses: " + e.getMessage());
    }
}
