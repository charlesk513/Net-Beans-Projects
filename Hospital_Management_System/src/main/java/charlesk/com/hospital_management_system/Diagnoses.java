    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findActionPerformed
    String diagnosis_id = txt_diagnoses_id.getText().trim();

    if(diagnosis_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the Diagnosis ID to search");
        txt_diagnoses_id.requestFocus();
        return;
    }

    String sql = "SELECT * FROM diagnoses WHERE diagnosis_id = ?";

    try(Connection findCon = DatabaseConnection.getConnection(); PreparedStatement findPst = findCon.prepareStatement(sql)){

        findPst.setString(1, diagnosis_id);

        try(ResultSet findRs = findPst.executeQuery()){

            if(findRs.next()){
                displayDiagnosis(findRs);
            }else{
                JOptionPane.showMessageDialog(this, "No diagnosis found with ID " + diagnosis_id);
            }
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error searching diagnosis: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_findActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
    Object appointment = combo_appointment.getSelectedItem();
    String diagnosisName = txt_name.getText().trim();
    String symptoms = txt_symptoms.getText().trim();
    String treatmentPlan = txt_treatment_plan.getText().trim();

    if(appointment == null){
        JOptionPane.showMessageDialog(this, "Please select an appointment");
        combo_appointment.requestFocus();
        return;
    }else if(diagnosisName.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the diagnosis name");
        txt_name.requestFocus();
        return;
    }

    String appointment_id = appointment.toString().split(" - ")[0];
    String sql = "INSERT INTO diagnoses(appointment_id, diagnosis_name, symptoms, treatment_plan) VALUES (?, ?, ?, ?)";

    try(Connection saveCon = DatabaseConnection.getConnection(); PreparedStatement savePst = saveCon.prepareStatement(sql)){

        savePst.setString(1, appointment_id);
        savePst.setString(2, diagnosisName);

        if(symptoms.isEmpty()) savePst.setNull(3, java.sql.Types.VARCHAR);
        else savePst.setString(3, symptoms);

        if(treatmentPlan.isEmpty()) savePst.setNull(4, java.sql.Types.VARCHAR);
        else savePst.setString(4, treatmentPlan);

        int rows = savePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Diagnosis successfully saved");
            clear();
            loadDiagnoses();
            showResultsInTheTable();
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error while saving diagnosis: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_saveActionPerformed

