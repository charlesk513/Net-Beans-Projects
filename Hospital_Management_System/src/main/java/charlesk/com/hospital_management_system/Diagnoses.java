    private void btn_deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_deleteActionPerformed
    String diagnosis_id = txt_diagnoses_id.getText().trim();

    if(diagnosis_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter or select a Diagnosis ID to delete");
        txt_diagnoses_id.requestFocus();
        return;
    }

    int choice = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this diagnosis?", "Confirm deletion", JOptionPane.YES_NO_OPTION);

    if(choice != JOptionPane.YES_OPTION) return;

    String sql = "DELETE FROM diagnoses WHERE diagnosis_id = ?";

    try(Connection deleteCon = DatabaseConnection.getConnection(); PreparedStatement deletePst = deleteCon.prepareStatement(sql)){

        deletePst.setString(1, diagnosis_id);
        int rows = deletePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Diagnosis deleted successfully");
            clear();
            loadDiagnoses();
            showResultsInTheTable();
        }else{
            JOptionPane.showMessageDialog(this, "No diagnosis with ID " + diagnosis_id + " exists in the database");
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_deleteActionPerformed

