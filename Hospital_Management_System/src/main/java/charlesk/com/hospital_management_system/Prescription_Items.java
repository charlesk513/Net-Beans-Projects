    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findActionPerformed
    String item_id = txt_item_id.getText().trim();

    if(item_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the Item ID to search");
        txt_item_id.requestFocus();
        return;
    }

    String sql = "SELECT * FROM prescription_items WHERE item_id = ?";

    try(Connection findCon = DatabaseConnection.getConnection(); PreparedStatement findPst = findCon.prepareStatement(sql)){

        findPst.setString(1, item_id);

        try(ResultSet findRs = findPst.executeQuery()){

            if(findRs.next()){
                displayPrescriptionItem(findRs);
            }else{
                JOptionPane.showMessageDialog(this, "No prescription item found with ID " + item_id);
            }
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error searching prescription item: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_findActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
    Object prescription = combo_prescriptions.getSelectedItem();
    Object medicine = combo_medicine.getSelectedItem();
    String dosage = txt_dosage.getText().trim();
    String frequency = txt_frequency.getText().trim();
    String quantityText = txt_quantity.getText().trim();
    int durationDays = (Integer) spinner_duration.getValue();

    if(prescription == null){
        JOptionPane.showMessageDialog(this, "Please select a prescription");
        combo_prescriptions.requestFocus();
        return;
    }else if(medicine == null){
        JOptionPane.showMessageDialog(this, "Please select a medicine");
        combo_medicine.requestFocus();
        return;
    }else if(dosage.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the dosage");
        txt_dosage.requestFocus();
        return;
    }else if(frequency.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the frequency");
        txt_frequency.requestFocus();
        return;
    }else if(quantityText.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the quantity");
        txt_quantity.requestFocus();
        return;
    }

    int quantity;

    try{
        quantity = Integer.parseInt(quantityText);

        if(quantity <= 0){
            JOptionPane.showMessageDialog(this, "Quantity must be greater than zero");
            txt_quantity.requestFocus();
            return;
        }

    }catch(NumberFormatException e){
        JOptionPane.showMessageDialog(this, "Please enter a valid number for quantity");
        txt_quantity.requestFocus();
        return;
    }

    String prescription_id = prescription.toString().split(" - ")[0];
    String medicine_id = medicine.toString().split(" - ")[0];

    String sql = "INSERT INTO prescription_items(prescription_id, medicine_id, dosage, frequency, duration_days, quantity) VALUES (?, ?, ?, ?, ?, ?)";

    try(Connection saveCon = DatabaseConnection.getConnection(); PreparedStatement savePst = saveCon.prepareStatement(sql)){

        savePst.setString(1, prescription_id);
        savePst.setString(2, medicine_id);
        savePst.setString(3, dosage);
        savePst.setString(4, frequency);
        savePst.setInt(5, durationDays);
        savePst.setInt(6, quantity);

        int rows = savePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Prescription item successfully saved");
            clear();
            loadPrescriptionItems();
            showResultsInTheTable();
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error while saving prescription item: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_saveActionPerformed

