public void loadPrescriptions(){
    String sql = """
                 SELECT pr.prescription_id, 
                 CONCAT(p.first_name,' ', p.last_name) AS full_name 
                 FROM prescriptions pr 
                 INNER JOIN appointments a ON pr.appointment_id = a.appointment_id 
                 INNER JOIN patients p ON a.patient_id = p.patient_id 
                 ORDER BY pr.prescription_id
                 """;

    try(Connection prescriptionCon = DatabaseConnection.getConnection(); 
            PreparedStatement prescriptionPst = prescriptionCon.prepareStatement(sql); 
            ResultSet prescriptionRs = prescriptionPst.executeQuery())
    {

        combo_prescriptions.removeAllItems();

        while(prescriptionRs.next()){
            combo_prescriptions.addItem(prescriptionRs.getString("prescription_id") + " - " + prescriptionRs.getString("full_name"));
        }

        combo_prescriptions.setSelectedIndex(-1);

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading prescriptions: " + e.getMessage());
    }
}
public void loadMedicines(){
    String sql = "SELECT medicine_id, medicine_name FROM medicines ORDER BY medicine_name";

    try(Connection medicineCon = DatabaseConnection.getConnection(); PreparedStatement medicinePst = medicineCon.prepareStatement(sql); ResultSet medicineRs = medicinePst.executeQuery()){

        combo_medicine.removeAllItems();

        while(medicineRs.next()){
            combo_medicine.addItem(medicineRs.getString("medicine_id") + " - " + medicineRs.getString("medicine_name"));
        }

        combo_medicine.setSelectedIndex(-1);

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading medicines: " + e.getMessage());
    }
}

public void displayPrescriptionItem(ResultSet data) throws SQLException{
    txt_item_id.setText(data.getString("item_id"));
    selectPrescription(data.getString("prescription_id"));
    selectMedicine(data.getString("medicine_id"));
    txt_dosage.setText(data.getString("dosage"));
    txt_frequency.setText(data.getString("frequency"));
    spinner_duration.setValue(data.getInt("duration_days"));
    txt_quantity.setText(data.getString("quantity"));
}
public void selectPrescription(String prescription_id){
    for(int i = 0; i < combo_prescriptions.getItemCount(); i++){
        if(combo_prescriptions.getItemAt(i).startsWith(prescription_id + " - ")){
            combo_prescriptions.setSelectedIndex(i);
            break;
        }
    }
}
public void selectMedicine(String medicine_id){
    for(int i = 0; i < combo_medicine.getItemCount(); i++){
        if(combo_medicine.getItemAt(i).startsWith(medicine_id + " - ")){
            combo_medicine.setSelectedIndex(i);
            break;
        }
    }
}
public void clear() throws SQLException{
    txt_item_id.setText("");
    combo_prescriptions.setSelectedIndex(-1);
    combo_medicine.setSelectedIndex(-1);
    txt_dosage.setText("");
    txt_frequency.setText("");
    spinner_duration.setValue(1);
    txt_quantity.setText("");
}
public void displayCurrentRow() throws SQLException{
    displayPrescriptionItem(rs);
}
public final void loadPrescriptionItems(){
    String sql = "SELECT * FROM prescription_items ORDER BY item_id";

    try{
        if(rs != null) rs.close();
        if(pst != null) pst.close();
        if(con != null) con.close();

        con = DatabaseConnection.getConnection();
        pst = con.prepareStatement(sql, ResultSet.TYPE_SCROLL_INSENSITIVE, ResultSet.CONCUR_READ_ONLY);
        rs = pst.executeQuery();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading prescription items: " + e.getMessage());
    }
}
public final void showResultsInTheTable(){
    try{
        DefaultTableModel model = (DefaultTableModel) prescription_items_table.getModel();
        model.setRowCount(0);

        while(rs.next()){
            Object[] row = {
                rs.getString("item_id"),
                rs.getString("prescription_id"),
                rs.getString("medicine_id"),
                rs.getString("dosage"),
                rs.getString("frequency"),
                rs.getInt("duration_days"),
                rs.getInt("quantity")
            };

            model.addRow(row);
        }

        rs.beforeFirst();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading prescription items: " + e.getMessage());
    }
}

