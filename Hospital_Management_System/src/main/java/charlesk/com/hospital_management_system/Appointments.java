    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findActionPerformed
    String appointment_id = txt_appointment_id.getText().trim();

    if(appointment_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the Appointment ID to search");
        txt_appointment_id.requestFocus();
        return;
    }

    String sql = "SELECT * FROM appointments WHERE appointment_id = ?";

    try(Connection findCon = DatabaseConnection.getConnection(); PreparedStatement findPst = findCon.prepareStatement(sql)){

        findPst.setString(1, appointment_id);

        try(ResultSet findRs = findPst.executeQuery()){

            if(findRs.next()){
                displayAppointment(findRs);
            }else{
                JOptionPane.showMessageDialog(this, "No appointment found with ID " + appointment_id);
            }
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error searching appointment: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_findActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
    Object patient = combo_patient.getSelectedItem();
    Object doctor = combo_doctor.getSelectedItem();
    Object status = combo_status.getSelectedItem();
    java.util.Date selectedDate = appointment_date.getDate();
    java.util.Date selectedTime = (java.util.Date) spinner_appointment_time.getValue();

    if(patient == null){
        JOptionPane.showMessageDialog(this, "Please select a patient");
        combo_patient.requestFocus();
        return;
    }else if(doctor == null){
        JOptionPane.showMessageDialog(this, "Please select a doctor");
        combo_doctor.requestFocus();
        return;
    }else if(selectedDate == null){
        JOptionPane.showMessageDialog(this, "Please select the appointment date");
        return;
    }else if(selectedTime == null){
        JOptionPane.showMessageDialog(this, "Please select the appointment time");
        return;
    }else if(status == null){
        JOptionPane.showMessageDialog(this, "Please select the appointment status");
        combo_status.requestFocus();
        return;
    }

    String patient_id = patient.toString().split(" - ")[0];
    String doctor_id = doctor.toString().split(" - ")[0];

    java.sql.Date appointmentDate = new java.sql.Date(selectedDate.getTime());
    java.sql.Time appointmentTime = new java.sql.Time(selectedTime.getTime());

    String sql = "INSERT INTO appointments(patient_id, doctor_id, appointment_date, appointment_time, status) VALUES (?, ?, ?, ?, ?)";

    try(Connection saveCon = DatabaseConnection.getConnection(); PreparedStatement savePst = saveCon.prepareStatement(sql)){

        savePst.setString(1, patient_id);
        savePst.setString(2, doctor_id);
        savePst.setDate(3, appointmentDate);
        savePst.setTime(4, appointmentTime);
        savePst.setString(5, status.toString());

        int rows = savePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Appointment successfully saved");
            clear();
            loadAppointments();
            showResultsInTheTable();
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error while saving appointment: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_saveActionPerformed

