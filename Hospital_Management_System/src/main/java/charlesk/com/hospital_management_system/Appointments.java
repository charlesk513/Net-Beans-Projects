    private void btn_deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_deleteActionPerformed
    String appointment_id = txt_appointment_id.getText().trim();

    if(appointment_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter or select an Appointment ID to delete");
        txt_appointment_id.requestFocus();
        return;
    }

    int choice = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this appointment?", "Confirm deletion", JOptionPane.YES_NO_OPTION);

    if(choice != JOptionPane.YES_OPTION) return;

    String sql = "DELETE FROM appointments WHERE appointment_id = ?";

    try(Connection deleteCon = DatabaseConnection.getConnection(); PreparedStatement deletePst = deleteCon.prepareStatement(sql)){

        deletePst.setString(1, appointment_id);
        int rows = deletePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Appointment deleted successfully");
            clear();
            loadAppointments();
            showResultsInTheTable();
        }else{
            JOptionPane.showMessageDialog(this, "No appointment with ID " + appointment_id + " exists in the database");
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_deleteActionPerformed

