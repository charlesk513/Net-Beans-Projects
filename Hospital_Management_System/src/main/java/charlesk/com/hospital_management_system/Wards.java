    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
    Object department = combo_department.getSelectedItem();
    String wardName = txt_name.getText().trim();
    String capacity = txt_capacity.getText().trim();
    String wardType = txt_ward_type.getText().trim();

    if(department == null){
        JOptionPane.showMessageDialog(this, "Please select a department");
        combo_department.requestFocus();
        return;
    }else if(wardName.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the ward name");
        txt_name.requestFocus();
        return;
    }else if(capacity.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the ward capacity");
        txt_capacity.requestFocus();
        return;
    }else if(wardType.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the ward type");
        txt_ward_type.requestFocus();
        return;
    }

    int wardCapacity;

    try{
        wardCapacity = Integer.parseInt(capacity);

        if(wardCapacity <= 0){
            JOptionPane.showMessageDialog(this, "Ward capacity must be greater than zero");
            txt_capacity.requestFocus();
            return;
        }

    }catch(NumberFormatException e){
        JOptionPane.showMessageDialog(this, "Please enter a valid number for capacity");
        txt_capacity.requestFocus();
        return;
    }

    String department_id = department.toString().split(" - ")[0];
    String sql = "INSERT INTO wards(department_id, ward_name, capacity, ward_type) VALUES (?, ?, ?, ?)";

    try(Connection saveCon = DatabaseConnection.getConnection(); PreparedStatement savePst = saveCon.prepareStatement(sql)){

        savePst.setString(1, department_id);
        savePst.setString(2, wardName);
        savePst.setInt(3, wardCapacity);
        savePst.setString(4, wardType);

        int rows = savePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Ward successfully saved");
            clear();
            loadWards();
            showResultsInTheTable();
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error while saving ward: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_saveActionPerformed

