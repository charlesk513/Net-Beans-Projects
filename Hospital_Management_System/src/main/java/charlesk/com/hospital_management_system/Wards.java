    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findActionPerformed
    String ward_id = txt_ward_id.getText().trim();

    if(ward_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the Ward ID to search");
        txt_ward_id.requestFocus();
        return;
    }

    String sql = "SELECT * FROM wards WHERE ward_id = ?";

    try(Connection findCon = DatabaseConnection.getConnection(); PreparedStatement findPst = findCon.prepareStatement(sql)){

        findPst.setString(1, ward_id);

        try(ResultSet findRs = findPst.executeQuery()){

            if(findRs.next()){
                displayWard(findRs);
            }else{
                JOptionPane.showMessageDialog(this, "No ward found with ID " + ward_id);
            }
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error searching ward: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_findActionPerformed

