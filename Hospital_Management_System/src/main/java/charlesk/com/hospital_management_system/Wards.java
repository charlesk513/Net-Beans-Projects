public void loadDepartments(){
    String sql = "SELECT department_id, department_name FROM departments ORDER BY department_name";

    try(Connection departmentCon = DatabaseConnection.getConnection(); PreparedStatement departmentPst = departmentCon.prepareStatement(sql); ResultSet departmentRs = departmentPst.executeQuery()){
        combo_department.removeAllItems();

        while(departmentRs.next()){
            combo_department.addItem(departmentRs.getString("department_id") + " - " + departmentRs.getString("department_name"));
        }

        combo_department.setSelectedIndex(-1);

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading departments: " + e.getMessage());
    }
}
public void displayWard(ResultSet data) throws SQLException{
    txt_ward_id.setText(data.getString("ward_id"));
    selectDepartment(data.getString("department_id"));
    txt_name.setText(data.getString("ward_name"));
    txt_capacity.setText(data.getString("capacity"));
    txt_ward_type.setText(data.getString("ward_type"));
}
public void selectDepartment(String department_id){
    for(int i = 0; i < combo_department.getItemCount(); i++){
        if(combo_department.getItemAt(i).startsWith(department_id + " - ")){
            combo_department.setSelectedIndex(i);
            break;
        }
    }
}
public void clear() throws SQLException{
    txt_ward_id.setText("");
    combo_department.setSelectedIndex(-1);
    txt_name.setText("");
    txt_capacity.setText("");
    txt_ward_type.setText("");
}
public void displayCurrentRow() throws SQLException{
    displayWard(rs);
}
public final void loadWards(){
    String sql = "SELECT * FROM wards ORDER BY ward_id";

    try{
        if(rs != null) rs.close();
        if(pst != null) pst.close();
        if(con != null) con.close();

        con = DatabaseConnection.getConnection();
        pst = con.prepareStatement(sql, ResultSet.TYPE_SCROLL_INSENSITIVE, ResultSet.CONCUR_READ_ONLY);
        rs = pst.executeQuery();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading wards: " + e.getMessage());
    }
}
public final void showResultsInTheTable(){
    try{
        DefaultTableModel model = (DefaultTableModel) ward_table.getModel();
        model.setRowCount(0);

        while(rs.next()){
            Object[] row = {
                rs.getString("ward_id"),
                rs.getString("department_id"),
                rs.getString("ward_name"),
                rs.getInt("capacity"),
                rs.getString("ward_type")
            };

            model.addRow(row);
        }

        rs.beforeFirst();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading wards: " + e.getMessage());
    }
}
