    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findActionPerformed
    String medicine_id = txt_medicine_id.getText().trim();

    if(medicine_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the Medicine ID to search");
        txt_medicine_id.requestFocus();
        return;
    }

    String sql = "SELECT * FROM medicines WHERE medicine_id = ?";

    try(Connection findCon = DatabaseConnection.getConnection(); PreparedStatement findPst = findCon.prepareStatement(sql)){

        findPst.setString(1, medicine_id);

        try(ResultSet findRs = findPst.executeQuery()){

            if(findRs.next()){
                displayMedicine(findRs);
            }else{
                JOptionPane.showMessageDialog(this, "No medicine found with ID " + medicine_id);
            }
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error searching medicine: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_findActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
    String medicineName = txt_name.getText().trim();
    String form = txt_form.getText().trim();
    String unitPriceText = txt_unit_price.getText().trim();
    String stockText = txt_stock_quantity.getText().trim();

    if(medicineName.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the medicine name");
        txt_name.requestFocus();
        return;
    }else if(form.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the medicine form");
        txt_form.requestFocus();
        return;
    }else if(unitPriceText.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the unit price");
        txt_unit_price.requestFocus();
        return;
    }else if(stockText.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the stock quantity");
        txt_stock_quantity.requestFocus();
        return;
    }

    BigDecimal unitPrice;
    int stockQuantity;

    try{
        unitPrice = new BigDecimal(unitPriceText);

        if(unitPrice.compareTo(BigDecimal.ZERO) <= 0){
            JOptionPane.showMessageDialog(this, "Unit price must be greater than zero");
            txt_unit_price.requestFocus();
            return;
        }

    }catch(NumberFormatException e){
        JOptionPane.showMessageDialog(this, "Please enter a valid unit price");
        txt_unit_price.requestFocus();
        return;
    }

    try{
        stockQuantity = Integer.parseInt(stockText);

        if(stockQuantity < 0){
            JOptionPane.showMessageDialog(this, "Stock quantity cannot be negative");
            txt_stock_quantity.requestFocus();
            return;
        }

    }catch(NumberFormatException e){
        JOptionPane.showMessageDialog(this, "Please enter a valid stock quantity");
        txt_stock_quantity.requestFocus();
        return;
    }

    String sql = "INSERT INTO medicines(medicine_name, form, unit_price, stock_quantity) VALUES (?, ?, ?, ?)";

    try(Connection saveCon = DatabaseConnection.getConnection(); PreparedStatement savePst = saveCon.prepareStatement(sql)){

        savePst.setString(1, medicineName);
        savePst.setString(2, form);
        savePst.setBigDecimal(3, unitPrice);
        savePst.setInt(4, stockQuantity);

        int rows = savePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Medicine successfully saved");
            clear();
            loadMedicines();
            showResultsInTheTable();
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error while saving medicine: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_saveActionPerformed

