    private void btn_deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_deleteActionPerformed
    String medicine_id = txt_medicine_id.getText().trim();

    if(medicine_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter or select a Medicine ID to delete");
        txt_medicine_id.requestFocus();
        return;
    }

    int choice = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this medicine?", "Confirm deletion", JOptionPane.YES_NO_OPTION);

    if(choice != JOptionPane.YES_OPTION) return;

    String sql = "DELETE FROM medicines WHERE medicine_id = ?";

    try(Connection deleteCon = DatabaseConnection.getConnection(); PreparedStatement deletePst = deleteCon.prepareStatement(sql)){

        deletePst.setString(1, medicine_id);

        int rows = deletePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Medicine deleted successfully");
            clear();
            loadMedicines();
            showResultsInTheTable();
        }else{
            JOptionPane.showMessageDialog(this, "No medicine with ID " + medicine_id + " exists in the database");
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_deleteActionPerformed

