public void displayCurrentRow() throws SQLException{
    displayMedicine(rs);
}
public final void loadMedicines(){
    String sql = "SELECT * FROM medicines ORDER BY medicine_id";

    try{
        if(rs != null) rs.close();
        if(pst != null) pst.close();
        if(con != null) con.close();

        con = DatabaseConnection.getConnection();
        pst = con.prepareStatement(sql, ResultSet.TYPE_SCROLL_INSENSITIVE, ResultSet.CONCUR_READ_ONLY);
        rs = pst.executeQuery();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading medicines: " + e.getMessage());
    }
}
public final void showResultsInTheTable(){
    try{
        DefaultTableModel model = (DefaultTableModel) medicines_table.getModel();
        model.setRowCount(0);

        while(rs.next()){
            Object[] row = {
                rs.getString("medicine_id"),
                rs.getString("medicine_name"),
                rs.getString("form"),
                rs.getBigDecimal("unit_price"),
                rs.getInt("stock_quantity")
            };

            model.addRow(row);
        }

        rs.beforeFirst();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading medicines: " + e.getMessage());
    }
}
