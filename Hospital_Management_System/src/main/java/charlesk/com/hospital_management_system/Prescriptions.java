public void loadAppointments(){
    String sql = """
                 SELECT a.appointment_id, 
                 CONCAT(p.first_name, ' ', p.last_name) AS full_name
                 FROM appointments a 
                 INNER JOIN patients p ON a.patient_id = p.patient_id 
                 ORDER BY a.appointment_id                                                                                                                                                    
                """;

    try(Connection appointmentCon = DatabaseConnection.getConnection(); 
            PreparedStatement appointmentPst = appointmentCon.prepareStatement(sql); 
            ResultSet appointmentRs = appointmentPst.executeQuery())
    {

        combo_appointment.removeAllItems();

        while(appointmentRs.next()){
            combo_appointment.addItem(appointmentRs.getString("appointment_id") + " - " + appointmentRs.getString("full_name"));
        }

        combo_appointment.setSelectedIndex(-1);

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading appointments: " + e.getMessage());
    }
}
public void displayPrescription(ResultSet data) throws SQLException{
    txt_prescription_id.setText(data.getString("prescription_id"));
    selectAppointment(data.getString("appointment_id"));
    prescribed_date.setDate(data.getDate("prescribed_date"));
    txt_notes.setText(data.getString("notes") == null ? "" : data.getString("notes"));
}
public void selectAppointment(String appointment_id){
    for(int i = 0; i < combo_appointment.getItemCount(); i++){
        if(combo_appointment.getItemAt(i).startsWith(appointment_id + " - ")){
            combo_appointment.setSelectedIndex(i);
            break;
        }
    }
}
public void clear() throws SQLException{
    txt_prescription_id.setText("");
    combo_appointment.setSelectedIndex(-1);
    prescribed_date.setDate(null);
    txt_notes.setText("");
}
public void displayCurrentRow() throws SQLException{
    displayPrescription(rs);
}
public final void loadPrescriptions(){
    String sql = "SELECT * FROM prescriptions ORDER BY prescription_id";

    try{
        if(rs != null) rs.close();
        if(pst != null) pst.close();
        if(con != null) con.close();

        con = DatabaseConnection.getConnection();
        pst = con.prepareStatement(sql, ResultSet.TYPE_SCROLL_INSENSITIVE, ResultSet.CONCUR_READ_ONLY);
        rs = pst.executeQuery();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading prescriptions: " + e.getMessage());
    }
}
public final void showResultsInTheTable(){
    try{
        DefaultTableModel model = (DefaultTableModel) prescriptions_table.getModel();
        model.setRowCount(0);

        while(rs.next()){
            Object[] row = {
                rs.getString("prescription_id"),
                rs.getString("appointment_id"),
                rs.getDate("prescribed_date"),
                rs.getString("notes")
            };

            model.addRow(row);
        }

        rs.beforeFirst();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading prescriptions: " + e.getMessage());
    }
}
