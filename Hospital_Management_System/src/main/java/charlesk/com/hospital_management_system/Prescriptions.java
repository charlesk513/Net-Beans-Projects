    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findActionPerformed
    String prescription_id = txt_prescription_id.getText().trim();

    if(prescription_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the Prescription ID to search");
        txt_prescription_id.requestFocus();
        return;
    }

    String sql = "SELECT * FROM prescriptions WHERE prescription_id = ?";

    try(Connection findCon = DatabaseConnection.getConnection(); PreparedStatement findPst = findCon.prepareStatement(sql)){

        findPst.setString(1, prescription_id);

        try(ResultSet findRs = findPst.executeQuery()){

            if(findRs.next()){
                displayPrescription(findRs);
            }else{
                JOptionPane.showMessageDialog(this, "No prescription found with ID " + prescription_id);
            }
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error searching prescription: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_findActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
    Object appointment = combo_appointment.getSelectedItem();
    java.util.Date selectedDate = prescribed_date.getDate();
    String notes = txt_notes.getText().trim();

    if(appointment == null){
        JOptionPane.showMessageDialog(this, "Please select an appointment");
        combo_appointment.requestFocus();
        return;
    }else if(selectedDate == null){
        JOptionPane.showMessageDialog(this, "Please select the prescribed date");
        return;
    }

    String appointment_id = appointment.toString().split(" - ")[0];
    java.sql.Date prescribedDate = new java.sql.Date(selectedDate.getTime());

    String sql = "INSERT INTO prescriptions(appointment_id, prescribed_date, notes) VALUES (?, ?, ?)";

    try(Connection saveCon = DatabaseConnection.getConnection(); PreparedStatement savePst = saveCon.prepareStatement(sql)){

        savePst.setString(1, appointment_id);
        savePst.setDate(2, prescribedDate);

        if(notes.isEmpty()) savePst.setNull(3, java.sql.Types.VARCHAR);
        else savePst.setString(3, notes);

        int rows = savePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Prescription successfully saved");
            clear();
            loadPrescriptions();
            showResultsInTheTable();
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error while saving prescription: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_saveActionPerformed

