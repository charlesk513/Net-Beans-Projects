    private void btn_deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_deleteActionPerformed
    String prescription_id = txt_prescription_id.getText().trim();

    if(prescription_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter or select a Prescription ID to delete");
        txt_prescription_id.requestFocus();
        return;
    }

    int choice = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this prescription?", "Confirm deletion", JOptionPane.YES_NO_OPTION);

    if(choice != JOptionPane.YES_OPTION) return;

    String sql = "DELETE FROM prescriptions WHERE prescription_id = ?";

    try(Connection deleteCon = DatabaseConnection.getConnection(); PreparedStatement deletePst = deleteCon.prepareStatement(sql)){

        deletePst.setString(1, prescription_id);
        int rows = deletePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Prescription deleted successfully");
            clear();
            loadPrescriptions();
            showResultsInTheTable();
        }else{
            JOptionPane.showMessageDialog(this, "No prescription with ID " + prescription_id + " exists in the database");
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_deleteActionPerformed

