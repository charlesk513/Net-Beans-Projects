    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findActionPerformed
    String test_id = txt_test_id.getText().trim();

    if(test_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the Test ID to search");
        txt_test_id.requestFocus();
        return;
    }

    String sql = "SELECT * FROM lab_tests WHERE test_id = ?";

    try(Connection findCon = DatabaseConnection.getConnection(); PreparedStatement findPst = findCon.prepareStatement(sql)){

        findPst.setString(1, test_id);

        try(ResultSet findRs = findPst.executeQuery()){

            if(findRs.next()){
                displayLabTest(findRs);
            }else{
                JOptionPane.showMessageDialog(this, "No lab test found with ID " + test_id);
            }
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error searching lab test: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_findActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
    Object appointment = combo_appointment.getSelectedItem();
    Object status = combo_status.getSelectedItem();
    String testName = txt_test_name.getText().trim();
    String result = txt_result.getText().trim();
    java.util.Date selectedDate = test_date.getDate();

    if(appointment == null){
        JOptionPane.showMessageDialog(this, "Please select an appointment");
        combo_appointment.requestFocus();
        return;
    }else if(testName.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the test name");
        txt_test_name.requestFocus();
        return;
    }else if(selectedDate == null){
        JOptionPane.showMessageDialog(this, "Please select the test date");
        return;
    }else if(status == null){
        JOptionPane.showMessageDialog(this, "Please select the test status");
        combo_status.requestFocus();
        return;
    }

    String appointment_id = appointment.toString().split(" - ")[0];
    java.sql.Date testDate = new java.sql.Date(selectedDate.getTime());

    String sql = "INSERT INTO lab_tests(appointment_id, test_name, test_date, result, status) VALUES (?, ?, ?, ?, ?)";

    try(Connection saveCon = DatabaseConnection.getConnection(); PreparedStatement savePst = saveCon.prepareStatement(sql)){

        savePst.setString(1, appointment_id);
        savePst.setString(2, testName);
        savePst.setDate(3, testDate);

        if(result.isEmpty()) savePst.setNull(4, java.sql.Types.VARCHAR);
        else savePst.setString(4, result);

        savePst.setString(5, status.toString());

        int rows = savePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Lab test successfully saved");
            clear();
            loadLabTests();
            showResultsInTheTable();
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error while saving lab test: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_saveActionPerformed

