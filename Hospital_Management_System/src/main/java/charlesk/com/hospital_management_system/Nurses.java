    private void btn_choose_imageActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_choose_imageActionPerformed
        JFileChooser chooser = new JFileChooser();

        FileNameExtensionFilter filter = new FileNameExtensionFilter("Image Files", "jpg", "jpeg", "png");

        chooser.setFileFilter(filter);

        int result = chooser.showOpenDialog(this);

        if(result == JFileChooser.APPROVE_OPTION){

            File selectedFile = chooser.getSelectedFile();

            try{
                Path nurseFolder = Paths.get("images", "nurses");

                Files.createDirectories(nurseFolder);

                String fileName = System.currentTimeMillis() + "_" + selectedFile.getName();

                Path destination = nurseFolder.resolve(fileName);

                Files.copy(
                    selectedFile.toPath(),
                    destination,
                    StandardCopyOption.REPLACE_EXISTING
                );

                imagePath = destination.toString();

                displayImage(imagePath);

            }catch(IOException e){
                JOptionPane.showMessageDialog(this, "Error copying image: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btn_choose_imageActionPerformed

