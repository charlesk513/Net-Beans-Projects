public final void loadNurses(){
    String sql = "SELECT * FROM nurses ORDER BY nurse_id";

    try{
        con = DatabaseConnection.getConnection();
        pst = con.prepareStatement(sql, ResultSet.TYPE_SCROLL_INSENSITIVE, ResultSet.CONCUR_READ_ONLY);
        rs = pst.executeQuery();
    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading nurses information: " + e.getMessage());
    }
}
public final void showResultsInTheTable(){
    try{
        DefaultTableModel model = (DefaultTableModel) nurses_table.getModel();
        model.setRowCount(0);

        while(rs.next()){
            Object[] row = {
                rs.getString("nurse_id"),
                rs.getString("department_id"),
                rs.getString("first_name"),
                rs.getString("last_name"),
                rs.getString("phone"),
                rs.getString("email"),
                rs.getString("qualification"),
                rs.getDate("date_of_birth"),
                rs.getString("gender")
            };
            model.addRow(row);
        }

        rs.beforeFirst();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading nurses: " + e.getMessage());
    }
}
public void loadDepartments(){
    String sql = "SELECT department_id, department_name FROM departments ORDER BY department_id";

    try(Connection con = DatabaseConnection.getConnection(); 
            PreparedStatement pst = con.prepareStatement(sql); 
            ResultSet rs = pst.executeQuery())
    {
        combo_department.removeAllItems();

        while(rs.next()){
            combo_department.addItem(rs.getString("department_id") + " - " + rs.getString("department_name"));
        }

        combo_department.setSelectedIndex(-1);

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading departments: " + e.getMessage());
    }
}
public void displayImage(String path){

    if(path == null || path.trim().isEmpty()){
        lbl_image.setIcon(null);
        lbl_image.setText("No Image");
        return;
    }

    File imageFile = new File(path);

    if(!imageFile.exists()){
        lbl_image.setIcon(null);
        lbl_image.setText("Image Not Found");
        return;
    }

    ImageIcon icon = new ImageIcon(path);

    Image image = icon.getImage().getScaledInstance(
        lbl_image.getWidth(),
        lbl_image.getHeight(),
        Image.SCALE_SMOOTH
    );

    lbl_image.setText("");
    lbl_image.setIcon(new ImageIcon(image));
}

