    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findActionPerformed

    String nurse_id = txt_nurse_id.getText().trim();

    if(nurse_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the Nurse ID to search");
        txt_nurse_id.requestFocus();
        return;
    }

    String sql = "SELECT * FROM nurses WHERE nurse_id = ?";

    try(Connection searchCon = DatabaseConnection.getConnection(); PreparedStatement searchPst = searchCon.prepareStatement(sql)){

        searchPst.setString(1, nurse_id);

        try(ResultSet searchRs = searchPst.executeQuery()){

            if(searchRs.next()){
                txt_nurse_id.setText(searchRs.getString("nurse_id"));
                combo_department.setSelectedItem(searchRs.getString("department_id"));
                txt_firstname.setText(searchRs.getString("first_name"));
                txt_surname.setText(searchRs.getString("last_name"));
                txt_phone.setText(searchRs.getString("phone"));
                txt_email.setText(searchRs.getString("email"));
                txt_qualification.setText(searchRs.getString("qualification"));
                date_chooser.setDate(searchRs.getDate("date_of_birth"));
                combo_gender.setSelectedItem(searchRs.getString("gender"));
            }else{
                JOptionPane.showMessageDialog(this, "No nurse found with ID " + nurse_id);
            }
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error searching nurse: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_findActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed

    String department_id = (String)combo_department.getSelectedItem();
    String firstname = txt_firstname.getText().trim();
    String surname = txt_surname.getText().trim();
    String phone = txt_phone.getText().trim();
    String email = txt_email.getText().trim();
    String qualification = txt_qualification.getText().trim();
    Object selectedGender = combo_gender.getSelectedItem();
    java.util.Date selectedDate = date_chooser.getDate();

    if(department_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please fill in the department ID");
        combo_department.requestFocus();
        return;
    }else if(firstname.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please fill in the firstname");
        txt_firstname.requestFocus();
        return;
    }else if(surname.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please fill in the surname");
        txt_surname.requestFocus();
        return;
    }else if(phone.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please fill in the phone");
        txt_phone.requestFocus();
        return;
    }else if(email.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please fill in the email");
        txt_email.requestFocus();
        return;
    }else if(qualification.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please fill in the qualification");
        txt_qualification.requestFocus();
        return;
    }else if(selectedDate == null){
        JOptionPane.showMessageDialog(this, "Please select date of birth");
        return;
    }else if(selectedGender == null){
        JOptionPane.showMessageDialog(this, "Please select gender");
        combo_gender.requestFocus();
        return;
    }

    String gender = selectedGender.toString();
    java.sql.Date dob = new java.sql.Date(selectedDate.getTime());
    String sql = "INSERT INTO nurses(department_id, first_name, last_name, phone, email, qualification, date_of_birth, gender) VALUES (?, ?, ?, ?, ?, ?, ?, ?)";

    try(Connection con = DatabaseConnection.getConnection(); PreparedStatement pst = con.prepareStatement(sql)){

        pst.setString(1, department_id);
        pst.setString(2, firstname);
        pst.setString(3, surname);
        pst.setString(4, phone);
        pst.setString(5, email);
        pst.setString(6, qualification);
        pst.setDate(7, dob);
        pst.setString(8, gender);

        int rows = pst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Nurse successfully saved");
            clear();
            loadNurses();
            showResultsInTheTable();
            txt_surname.requestFocus();
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error while saving nurse: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_saveActionPerformed

