    private void btn_deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_deleteActionPerformed
    String room_id = txt_room_id.getText().trim();

    if(room_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter or select a Room ID to delete");
        txt_room_id.requestFocus();
        return;
    }

    int choice = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this room?", "Confirm deletion", JOptionPane.YES_NO_OPTION);

    if(choice != JOptionPane.YES_OPTION) return;

    String sql = "DELETE FROM rooms WHERE room_id = ?";

    try(Connection deleteCon = DatabaseConnection.getConnection(); PreparedStatement deletePst = deleteCon.prepareStatement(sql)){

        deletePst.setString(1, room_id);
        int rows = deletePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Room deleted successfully");
            clear();
            loadRooms();
            showResultsInTheTable();
        }else{
            JOptionPane.showMessageDialog(this, "No room with ID " + room_id + " exists in the database");
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Database error: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_deleteActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
    Object ward = combo_ward.getSelectedItem();
    Object status = combo_status.getSelectedItem();
    String roomNumber = txt_room_number.getText().trim();
    String roomType = txt_room_type.getText().trim();
    String bedCapacity = txt_bed_capacity.getText().trim();

    if(ward == null){
        JOptionPane.showMessageDialog(this, "Please select a ward");
        combo_ward.requestFocus();
        return;
    }else if(roomNumber.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the room number");
        txt_room_number.requestFocus();
        return;
    }else if(roomType.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the room type");
        txt_room_type.requestFocus();
        return;
    }else if(bedCapacity.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the bed capacity");
        txt_bed_capacity.requestFocus();
        return;
    }else if(status == null){
        JOptionPane.showMessageDialog(this, "Please select the room status");
        combo_status.requestFocus();
        return;
    }

    int capacity;

    try{
        capacity = Integer.parseInt(bedCapacity);

        if(capacity <= 0){
            JOptionPane.showMessageDialog(this, "Bed capacity must be greater than zero");
            txt_bed_capacity.requestFocus();
            return;
        }

    }catch(NumberFormatException e){
        JOptionPane.showMessageDialog(this, "Please enter a valid number for bed capacity");
        txt_bed_capacity.requestFocus();
        return;
    }

    String ward_id = ward.toString().split(" - ")[0];
    String sql = "INSERT INTO rooms(ward_id, room_number, room_type, bed_capacity, status) VALUES (?, ?, ?, ?, ?)";

    try(Connection saveCon = DatabaseConnection.getConnection(); PreparedStatement savePst = saveCon.prepareStatement(sql)){

        savePst.setString(1, ward_id);
        savePst.setString(2, roomNumber);
        savePst.setString(3, roomType);
        savePst.setInt(4, capacity);
        savePst.setString(5, status.toString());

        int rows = savePst.executeUpdate();

        if(rows > 0){
            JOptionPane.showMessageDialog(this, "Room successfully saved");
            clear();
            loadRooms();
            showResultsInTheTable();
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error while saving room: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_saveActionPerformed

