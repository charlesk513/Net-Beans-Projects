    private void btn_findActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_findActionPerformed
    String room_id = txt_room_id.getText().trim();

    if(room_id.isEmpty()){
        JOptionPane.showMessageDialog(this, "Please enter the Room ID to search");
        txt_room_id.requestFocus();
        return;
    }

    String sql = "SELECT * FROM rooms WHERE room_id = ?";

    try(Connection findCon = DatabaseConnection.getConnection(); PreparedStatement findPst = findCon.prepareStatement(sql)){

        findPst.setString(1, room_id);

        try(ResultSet findRs = findPst.executeQuery()){

            if(findRs.next()){
                displayRoom(findRs);
            }else{
                JOptionPane.showMessageDialog(this, "No room found with ID " + room_id);
            }
        }

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error searching room: " + e.getMessage());
    }
    }//GEN-LAST:event_btn_findActionPerformed

