public void loadWards(){
    String sql = "SELECT ward_id, ward_name FROM wards ORDER BY ward_name";

    try(Connection wardCon = DatabaseConnection.getConnection(); PreparedStatement wardPst = wardCon.prepareStatement(sql); ResultSet wardRs = wardPst.executeQuery()){
        combo_ward.removeAllItems();

        while(wardRs.next()){
            combo_ward.addItem(wardRs.getString("ward_id") + " - " + wardRs.getString("ward_name"));
        }

        combo_ward.setSelectedIndex(-1);

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading wards: " + e.getMessage());
    }
}
public void displayRoom(ResultSet data) throws SQLException{
    txt_room_id.setText(data.getString("room_id"));
    selectWard(data.getString("ward_id"));
    txt_room_number.setText(data.getString("room_number"));
    txt_room_type.setText(data.getString("room_type"));
    txt_bed_capacity.setText(data.getString("bed_capacity"));
    combo_status.setSelectedItem(data.getString("status"));
}
public void selectWard(String ward_id){
    for(int i = 0; i < combo_ward.getItemCount(); i++){
        if(combo_ward.getItemAt(i).startsWith(ward_id + " - ")){
            combo_ward.setSelectedIndex(i);
            break;
        }
    }
}
public void clear() throws SQLException{
    txt_room_id.setText("");
    combo_ward.setSelectedIndex(-1);
    txt_room_number.setText("");
    txt_room_type.setText("");
    txt_bed_capacity.setText("");
    combo_status.setSelectedIndex(-1);
}
public void displayCurrentRow() throws SQLException{
    displayRoom(rs);
}
public final void loadRooms(){
    String sql = "SELECT * FROM rooms ORDER BY room_id";

    try{
        if(rs != null) rs.close();
        if(pst != null) pst.close();
        if(con != null) con.close();

        con = DatabaseConnection.getConnection();
        pst = con.prepareStatement(sql, ResultSet.TYPE_SCROLL_INSENSITIVE, ResultSet.CONCUR_READ_ONLY);
        rs = pst.executeQuery();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading rooms: " + e.getMessage());
    }
}
public final void showResultsInTheTable(){
    try{
        DefaultTableModel model = (DefaultTableModel) rooms_table.getModel();
        model.setRowCount(0);

        while(rs.next()){
            Object[] row = {
                rs.getString("room_id"),
                rs.getString("ward_id"),
                rs.getString("room_number"),
                rs.getString("room_type"),
                rs.getInt("bed_capacity"),
                rs.getString("status")
            };

            model.addRow(row);
        }

        rs.beforeFirst();

    }catch(SQLException e){
        JOptionPane.showMessageDialog(this, "Error loading rooms: " + e.getMessage());
    }
}
