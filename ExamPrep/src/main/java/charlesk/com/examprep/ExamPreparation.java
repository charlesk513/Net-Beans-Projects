    private void btn_loginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_loginActionPerformed
        String username = String.valueOf(new StringBuilder(txt_username.getText().trim()));
        String password = String.valueOf(txt_password.getPassword());

        if(username.isEmpty()){
            JOptionPane.showMessageDialog(null, "Please enter the username");
            txt_username.requestFocus();
            return;
        } else if(password.isEmpty()){
            JOptionPane.showMessageDialog(null, "Please enter the password");
            txt_password.requestFocus();
            return;
        }

        String sql = """
        SELECT username, password 
        FROM login
        WHERE username = ? AND password = ?);
        """;
        try(Connection conn = DatabaseConnection.getConnection();
            PreparedStatement pst = conn.prepareStatement(sql);
        ){
            pst.setString(1, username);
            pst.setString(2, password);
            int result = pst.executeUpdate();

            if(result > 0){
                JOptionPane.showMessageDialog(null, "Successfully saved into the database");
                ExamPreparation login = new ExamPreparation();
                login.setVisible(true);
                this.dispose();
            } else
                JOptionPane.showMessageDialog(null, "Something went wrong when saving");
            
        } catch(SQLException e){
            e.printStackTrace();
        }

    }//GEN-LAST:event_btn_loginActionPerformed

